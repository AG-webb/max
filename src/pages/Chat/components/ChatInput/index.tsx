import { useSending } from "@/features/sending/hooks/useService";
import { sendMessage } from "@/features/sending/model/sendingThunks";
import type { ChatType } from "@/types";
import { useState } from "react";

const ChatInput = ({
  chatId,
  chatType,
}: {
  chatId: string;
  chatType: ChatType;
}) => {
  const [inputValue, setInputValue] = useState("");
  const { dispatch } = useSending();

  const handleSendMessage = () => {
    if (inputValue !== "") {
      dispatch(sendMessage({ chatId, message: inputValue, chatType }));
      setInputValue("");
    }
  };

  return (
    <div className="chat-input bg-dark-primary rounded-2xl overflow-hidden grid grid-cols-[48px_1fr_96px] items-center">
      <div className="chat-input__attachment">
        <div className="chat-input__btn w-12 h-12 px-2 py-1 flex items-center justify-center cursor-pointer text-icon-tertiary">
          <svg width="24" height="24" viewBox="0 0 24 24">
            <path
              fill="currentColor"
              d="M18.561 13.453q.117-.435.228-.887l.024-.082c.455-1.803.88-3.757 1.183-5.212.362-1.742-.348-3.69-2.118-4.511a8.4 8.4 0 0 0-1.329-.5 8.4 8.4 0 0 0-1.4-.232c-1.944-.174-3.533 1.159-4.09 2.848a140 140 0 0 0-1.426 4.56 41 41 0 0 0-.445 1.709 181 181 0 0 0-.713 3.045c-.259 1.145.045 2.674 1.4 3.351.182.09.39.179.612.238.23.062.461.09.669.1 1.471.074 2.455-1.067 2.803-2.135.425-1.304 1.08-3.37 1.552-5.132l.04-.151a.99.99 0 0 0-.705-1.21 1.01 1.01 0 0 0-1.233.719l-.034.125c-.457 1.707-1.098 3.732-1.521 5.03-.184.564-.557.769-.8.757a1.3 1.3 0 0 1-.253-.034 1.3 1.3 0 0 1-.236-.096c-.247-.123-.48-.52-.343-1.122.195-.866.463-2.027.75-3.196a37 37 0 0 1 .424-1.596c.45-1.539.955-3.115 1.358-4.336.322-.975 1.16-1.558 2.012-1.482.396.036.763.092 1.062.172.298.08.643.214 1.005.382.775.36 1.21 1.284 1 2.29a130 130 0 0 1-1.125 4.977 1 1 0 0 0-.03.1q-.123.51-.253.993c-.369 1.378-.892 2.912-1.394 4.274-.704 1.909-2.534 3.067-4.383 2.722a12 12 0 0 1-.878-.196 13 13 0 0 1-1.121-.363c-1.747-.644-2.78-2.492-2.547-4.46a119 119 0 0 1 .817-5.637 1.004 1.004 0 0 0-.729-1.135.997.997 0 0 0-1.242.797c-.325 1.95-.604 3.812-.832 5.74-.327 2.765 1.116 5.567 3.84 6.571.432.16.872.305 1.296.419.334.09.681.165 1.03.23 2.954.55 5.639-1.32 6.625-3.996.512-1.388 1.058-2.986 1.45-4.448"
            ></path>
          </svg>
        </div>
      </div>
      <div className="chat-input__element h-full">
        <input
          className="w-full outline-none h-full"
          type="text"
          name="message"
          onChange={(e) => setInputValue(e.target.value)}
          onKeyUp={(e) => {
            if (e.code === "Enter") handleSendMessage();
          }}
          value={inputValue}
          placeholder="Message"
          autoComplete="off"
        />
      </div>
      <div className="chat-input__btns grid grid-cols-2">
        <div className="chat-input__btn w-12 h-12 px-2 py-1 flex items-center justify-center cursor-pointer text-icon-tertiary">
          <svg width="24" height="24" viewBox="0 0 24 24">
            <path
              fill="currentColor"
              d="M15.447 8.067a1 1 0 1 0-1.932.517l.388 1.45a1 1 0 0 0 1.932-.518zm-7.021.845a1 1 0 0 1 1.225.707l.389 1.45a1 1 0 0 1-1.932.517l-.389-1.449a1 1 0 0 1 .707-1.225"
            ></path>
            <path
              fill="currentColor"
              fillRule="evenodd"
              d="M7.216 3.67A37 37 0 0 1 9.9 2.825a37 37 0 0 1 2.75-.61l.068-.012c1.105-.207 2.039-.38 2.834-.411.86-.033 1.629.095 2.392.536.763.44 1.26 1.043 1.66 1.803.371.704.687 1.6 1.061 2.66l.023.066c.314.89.614 1.816.847 2.685.167.622.26.981.31 1.962.085 1.601-.58 3.502-1.505 5.105-.925 1.602-2.24 3.129-3.668 3.857-.875.445-1.232.545-1.854.711-.87.233-1.822.437-2.75.61l-.068.012c-1.105.207-2.039.381-2.835.412-.858.032-1.628-.096-2.39-.537-.764-.44-1.26-1.042-1.661-1.803-.371-.704-.687-1.6-1.061-2.66l-.023-.066a37 37 0 0 1-.847-2.685 37 37 0 0 1-.61-2.75l-.012-.067c-.207-1.106-.381-2.04-.412-2.835-.033-.86.096-1.629.537-2.392.44-.763 1.042-1.26 1.803-1.66.704-.371 1.6-.687 2.66-1.061zm3.203 1.086c-.803.215-1.678.497-2.538.8-1.143.404-1.9.673-2.459.968-.517.273-.797.534-1.003.891-.207.358-.293.73-.27 1.315.024.632.169 1.42.391 2.612.168.898.36 1.797.575 2.6a35 35 0 0 0 .802 2.537c.403 1.143.672 1.9.967 2.459.273.517.534.797.891 1.003.358.207.73.293 1.315.27.631-.024 1.42-.17 2.612-.391a35 35 0 0 0 2.6-.576l.063-.017a48 48 0 0 1-.156-.8l-.013-.068a51 51 0 0 1-.284-1.615 6 6 0 0 1-.262.076c-1.532.41-3.08.195-4.479-.463-.687-.323-.656-1.249-.011-1.648.329-.204.739-.206 1.096-.057.96.398 1.947.486 2.876.237q.356-.096.686-.252c.065-.519.22-1.013.503-1.505.441-.762 1.043-1.259 1.803-1.66.704-.371 1.6-.687 2.66-1.06l.066-.024q.383-.136.771-.265l-.017-.064a35 35 0 0 0-.801-2.538c-.403-1.143-.672-1.9-.967-2.459-.273-.517-.534-.797-.891-1.003-.358-.206-.73-.292-1.315-.27-.632.024-1.42.17-2.613.392-.897.167-1.796.36-2.598.575m8.19 10.852c-.695 1.203-1.557 2.207-2.37 2.785l-.064-.333c-.222-1.192-.367-1.981-.391-2.613-.023-.585.063-.957.27-1.314.206-.358.485-.619 1.003-.891.56-.295 1.315-.565 2.458-.968l.32-.111c-.093.993-.532 2.241-1.226 3.445"
              clipRule="evenodd"
            ></path>
          </svg>
        </div>
        {inputValue !== "" ? (
          <div className="chat-input__btn w-12 h-12 px-2 py-1 flex items-center justify-center cursor-pointer text-icon-tertiary">
            <button
              className="w-8 h-8 cursor-pointer rounded-full flex items-center justify-center bg-button-primary text-neutral-primary"
              type="button"
              onClick={handleSendMessage}
            >
              <svg width="24" height="24" viewBox="0 0 24 24">
                <path
                  fill="currentColor"
                  fill-rule="evenodd"
                  d="M5.29 11.705a1 1 0 0 1 .005-1.415l6.015-5.97a1 1 0 0 1 1.41.001l5.987 5.972a1 1 0 0 1-1.412 1.416l-4.28-4.27v11.533a1 1 0 1 1-2 0V7.43l-4.31 4.279a1 1 0 0 1-1.414-.005"
                  clip-rule="evenodd"
                ></path>
              </svg>
            </button>
          </div>
        ) : (
          <div className="chat-input__btn w-12 h-12 px-2 py-1 flex items-center justify-center cursor-pointer text-icon-tertiary">
            <svg width="24" height="24" viewBox="0 0 24 24">
              <path
                fill="currentColor"
                d="m12.967 19.253.159-.007c3.875-.179 6.867-3.272 7.114-7.045q.036-.548.059-1.096a.896.896 0 0 0-.908-.923.935.935 0 0 0-.932.894q-.022.5-.055 1.007c-.19 2.902-2.478 5.214-5.364 5.347q-.517.024-.99.024c-.314 0-.647-.008-.99-.024-2.887-.133-5.174-2.445-5.364-5.347q-.033-.506-.055-1.007a.935.935 0 0 0-.933-.894.896.896 0 0 0-.907.923q.023.548.059 1.096c.247 3.772 3.239 6.866 7.114 7.045l.16.007v1.838c0 .502.41.909.916.909a.913.913 0 0 0 .916-.91z"
              ></path>
              <path
                fill="currentColor"
                d="M12.05 2c2.837 0 4.84 2.417 4.986 5.026.033.599.055 1.214.055 1.792s-.022 1.194-.055 1.793c-.146 2.608-2.15 5.025-4.986 5.025-2.837 0-4.84-2.416-4.986-5.025-.034-.6-.056-1.215-.056-1.793s.022-1.193.056-1.792C7.209 4.416 9.213 2 12.05 2m0 2c-1.566 0-2.89 1.364-2.99 3.137a31 31 0 0 0-.052 1.681c0 .53.02 1.106.053 1.681.098 1.773 1.423 3.137 2.989 3.137s2.89-1.364 2.989-3.136c.032-.576.052-1.152.052-1.682s-.02-1.106-.052-1.681C14.94 5.364 13.615 4 12.049 4"
              ></path>
            </svg>
          </div>
        )}
      </div>
    </div>
  );
};

export default ChatInput;
